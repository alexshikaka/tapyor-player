// Мост между окном и системной частью приложения.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('app', {
  getVersion: () => ipcRenderer.invoke('get-version'),
  ytSearch: (query) => ipcRenderer.invoke('yt-search', query),
  ytStream: (id) => ipcRenderer.invoke('yt-stream', id),
  ytSearchMore: (query, count) => ipcRenderer.invoke('yt-search-more', query, count),
  ymStatus: () => ipcRenderer.invoke('ym-status'),
  ymLogin: () => ipcRenderer.invoke('ym-login'),
  ymLogout: () => ipcRenderer.invoke('ym-logout'),
  ymLoginBrowserStart: () => ipcRenderer.invoke('ym-login-browser-start'),
  ymLoginBrowserWait: () => ipcRenderer.invoke('ym-login-browser-wait'),
  ymLoginBrowserCancel: () => ipcRenderer.invoke('ym-login-browser-cancel'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  nowPlaying: (info) => ipcRenderer.send('now-playing', info),
  npPath: () => ipcRenderer.invoke('np-path'),
  updateGetState: () => ipcRenderer.invoke('update-get-state'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateDownload: () => ipcRenderer.invoke('update-download'),
  onUpdateState: (cb) => ipcRenderer.on('update-state', (e, st) => cb(st)),
  ymSearch: (q) => ipcRenderer.invoke('ym-search', q),
  ymStream: (id) => ipcRenderer.invoke('ym-stream', id),
  suggest: (part) => ipcRenderer.invoke('suggest', part),
  ymWaveStart: (settings) => ipcRenderer.invoke('ym-wave-start', settings),
  ymWaveMore: (lastId) => ipcRenderer.invoke('ym-wave-more', lastId),
  ymWaveFeedback: (type, trackKey, played) => ipcRenderer.send('ym-wave-feedback', type, trackKey, played),
  ymSearchPage: (q, page) => ipcRenderer.invoke('ym-search-page', q, page),
  ymStations: () => ipcRenderer.invoke('ym-stations'),
  ymWaveVariants: () => ipcRenderer.invoke('ym-wave-variants'),
  ymMy: () => ipcRenderer.invoke('ym-my'),
  ymLiked: () => ipcRenderer.invoke('ym-liked'),
  ymPlaylist: (pl) => ipcRenderer.invoke('ym-playlist', pl),
  ymArtist: (id) => ipcRenderer.invoke('ym-artist', id),
  ymLikeIds: () => ipcRenderer.invoke('ym-like-ids'),
  ymLike: (trackKey, on) => ipcRenderer.invoke('ym-like', trackKey, on),
  ytPlaylist: (listId) => ipcRenderer.invoke('yt-playlist', listId),
  resolveLink: (text) => ipcRenderer.invoke('resolve-link', text),
  matchLine: (line) => ipcRenderer.invoke('match-line', line),
  ymCreatePlaylist: (title, tracks) => ipcRenderer.invoke('ym-create-playlist', title, tracks),
  npChooseFolder: () => ipcRenderer.invoke('np-choose-folder'),
  npOpenFolder: () => ipcRenderer.invoke('np-open-folder'),
  logCopy: () => ipcRenderer.invoke('log-copy'),
  logOpen: () => ipcRenderer.invoke('log-open'),
  playerBusy: (busy) => ipcRenderer.send('player-busy', busy),
  getSetting: (key) => ipcRenderer.invoke('get-setting', key),
  setSetting: (key, value) => ipcRenderer.invoke('set-setting', key, value)
});
